#!/usr/bin/env node
/**
 * Writes src/live/jmuxerSource.ts: jmuxer's minified build as a string, so
 * the player page can inline it and the live view never needs the internet.
 *
 * Run after upgrading jmuxer:  node tools/embed-jmuxer.js
 */
const fs = require('fs');
const path = require('path');

const pkg = require('../node_modules/jmuxer/package.json');
const src = fs.readFileSync(path.join(__dirname, '../node_modules/jmuxer/dist/jmuxer.min.js'), 'utf8');
if (/<\/script/i.test(src)) throw new Error('jmuxer source contains </script; cannot inline safely');

const out =
  `// Generated by tools/embed-jmuxer.js from jmuxer@${pkg.version} (MIT, Samir Das).\n` +
  `// Do not edit by hand.\n` +
  `/* eslint-disable */\n` +
  `export const JMUXER_VERSION = ${JSON.stringify(pkg.version)};\n` +
  `export const JMUXER_SOURCE = ${JSON.stringify(src)};\n`;

fs.writeFileSync(path.join(__dirname, '../src/live/jmuxerSource.ts'), out);
console.log(`embedded jmuxer@${pkg.version}: ${src.length} bytes`);
